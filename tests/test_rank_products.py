def fake_encode_text(text):
    """
    Fake query embedding.

    Dimension is intentionally small so the test
    does not call Hugging Face.
    """

    return [
        1.0,
        0.0,
        0.0,
    ]


def make_fake_products(candidates):
    """
    Build fake product embeddings using the REAL
    product IDs found in style_kb_matched.jsonl.
    """

    products = {}

    # --------------------------------------------------------
    # Top
    # --------------------------------------------------------

    top_vectors = [
        [1.0, 0.0, 0.0],
        [0.8, 0.6, 0.0],
        [0.6, 0.8, 0.0],
    ]

    for i, candidate in enumerate(
        candidates["top"]
    ):
        vector = top_vectors[
            i % len(top_vectors)
        ]

        products[
            candidate["product_id"]
        ] = {
            "product_id":
                candidate["product_id"],

            "category":
                "top",

            "embedding":
                rp.normalize_embedding(
                    vector
                ),
        }

    # --------------------------------------------------------
    # Bottom
    # --------------------------------------------------------

    bottom_vectors = [
        [1.0, 0.0, 0.0],
        [0.9, 0.1, 0.0],
        [0.7, 0.3, 0.0],
    ]

    for i, candidate in enumerate(
        candidates["bottom"]
    ):
        vector = bottom_vectors[
            i % len(bottom_vectors)
        ]

        products[
            candidate["product_id"]
        ] = {
            "product_id":
                candidate["product_id"],

            "category":
                "bottom",

            "embedding":
                rp.normalize_embedding(
                    vector
                ),
        }

    return products


