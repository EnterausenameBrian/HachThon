# ============================================================
# Test 2
# Embedding normalization
# ============================================================

def test_normalize_embedding():

    embedding = (
        rp.normalize_embedding(
            [3.0, 4.0, 0.0]
        )
    )

    assert np.isclose(
        np.linalg.norm(
            embedding
        ),
        1.0,
    )

    assert np.allclose(
        embedding,
        [
            0.6,
            0.8,
            0.0,
        ],
    )


