# ============================================================
# Test 8
# Rank real Stage-1 candidates
# ============================================================

def test_rank_real_style_candidates():

    # REAL candidates generated by
    # build_style_lookup.py.
    candidates = (
        rp.load_style_candidates(
            "old_money"
        )
    )

    # Fake embeddings, but using the REAL product IDs.
    products = (
        make_fake_products(
            candidates
        )
    )

    query_embedding = (
        rp.normalize_embedding(
            [1.0, 0.0, 0.0]
        )
    )

    user_embeddings = [
        rp.normalize_embedding(
            [1.0, 0.0, 0.0]
        )
    ]

    results = (
        rp.rank_category(
            candidates=
                candidates["top"],

            products=
                products,

            user_embeddings=
                user_embeddings,

            query_embedding=
                query_embedding,

            top_m=3,
        )
    )

    assert len(results) == 3

    # Scores must be descending.
    final_scores = [
        item["final_score"]
        for item in results
    ]

    assert final_scores == sorted(
        final_scores,
        reverse=True,
    )

    # Output structure.
    for result in results:

        assert "product_id" in result
        assert "style_score" in result
        assert "user_score" in result
        assert "query_score" in result
        assert "final_score" in result


# ============================================================
# Test 9
# Full pipeline
# ============================================================

def test_full_ranking_pipeline(
    monkeypatch,
):

    # --------------------------------------------------------
    # Read REAL Stage-1 output
    # --------------------------------------------------------

    candidates = (
        rp.load_style_candidates(
            "old_money"
        )
    )

    fake_products = (
        make_fake_products(
            candidates
        )
    )

    # --------------------------------------------------------
    # Mock Hugging Face
    # --------------------------------------------------------

    monkeypatch.setattr(
        rp,
        "encode_text",
        fake_encode_text,
    )

    # --------------------------------------------------------
    # Mock product DB
    # --------------------------------------------------------

    monkeypatch.setattr(
        rp,
        "load_candidate_products",
        lambda product_ids:
            fake_products,
    )

    # --------------------------------------------------------
    # Mock user preference DB
    # --------------------------------------------------------

    def fake_user_preferences(
        user_id,
        category,
    ):

        if category == "top":

            return [
                rp.normalize_embedding(
                    [1.0, 0.0, 0.0]
                )
            ]

        return [
            rp.normalize_embedding(
                [0.9, 0.1, 0.0]
            )
        ]

    monkeypatch.setattr(
        rp,
        "load_user_preference_embeddings",
        fake_user_preferences,
    )

    # --------------------------------------------------------
    # Run COMPLETE second stage
    # --------------------------------------------------------

    result = rp.rank_products(
        user_id="test_user",

        style_name="old_money",

        query_text=(
            "A clean and slightly formal "
            "outfit for warm weather."
        ),

        top_m=3,
    )

    # --------------------------------------------------------
    # Verify final output
    # --------------------------------------------------------

    assert result[
        "user_id"
    ] == "test_user"

    assert result[
        "style"
    ] == "old_money"

    assert len(
        result["top"]
    ) == 3

    assert len(
        result["bottom"]
    ) == 3

    # Check final ranking.
    for category in [
        "top",
        "bottom",
    ]:

        scores = [
            item["final_score"]
            for item
            in result[category]
        ]

        assert scores == sorted(
            scores,
            reverse=True,
        )