# ============================================================
# Test 4
# User score = average cosine similarity
# ============================================================

def test_calculate_user_score():

    product_embedding = (
        rp.normalize_embedding(
            [1.0, 0.0, 0.0]
        )
    )

    user_embeddings = [
        rp.normalize_embedding(
            [1.0, 0.0, 0.0]
        ),
        rp.normalize_embedding(
            [0.0, 1.0, 0.0]
        ),
    ]

    score = (
        rp.calculate_user_score(
            product_embedding,
            user_embeddings,
        )
    )

    # Similarities:
    #
    # 1.0
    # 0.0
    #
    # average = 0.5

    assert np.isclose(
        score,
        0.5,
    )


